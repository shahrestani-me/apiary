def test_the_command_reports_the_stack_and_its_image(capsys):
    assert main([PROMPT, "--stack", "node"]) == 0

    out = capsys.readouterr().out
    assert "stack: node" in out
    assert "apiary-worker-node" in out


def test_the_command_writes_nothing(tmp_path, monkeypatch):
    """It used to write a project into a directory. A command that still did
    would be a second, dead generator that a contributor would reasonably read
    as the supported one."""
    monkeypatch.chdir(tmp_path)

    main([PROMPT])

    assert list(tmp_path.iterdir()) == []


def test_the_command_reports_a_refusal_instead_of_raising(capsys, monkeypatch):
    """The property this file has always protected: an operator gets a line and
    an exit code, not a traceback.

    A stack outside the contract is now rejected by argparse's `choices` before
    the function is reached, which is a better failure and not this one. So the
    refusal under test is the one argparse cannot see: a stack the contract
    allows and this host has no image configured for.
    """
    monkeypatch.setattr(
        "swarm.greenfield.scaffold.StackImages", lambda *a, **k: StackImages(images={})
    )

    assert main([PROMPT, "--stack", "node"]) == 1
    assert "APIARY_WORKER_IMAGES" in capsys.readouterr().err
